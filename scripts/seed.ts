/**
 * Seeds the catalog: 6 courses (phases, books, tasks), the All Access bundle,
 * the TEST100 coupon, default email templates, and the admin user.
 *
 *   npm run seed        → writes to your Supabase project (needs .env.local)
 *   npm run seed:sql    → regenerates supabase/seed.sql (same data as SQL)
 *   npm run content:sql → regenerates the course-content migration for existing databases
 *
 * Safe to run more than once: existing rows are never overwritten, so edits
 * made in the admin portal survive a re-seed.
 */
import { createHash } from "node:crypto";
import { config } from "dotenv";
import { createClient } from "@supabase/supabase-js";
import { BUNDLE, COURSES, TEST_COUPON, courseAllowances } from "./seed-data";
import { DEFAULT_TEMPLATES } from "../emails/defaults";

config({ path: ".env.local", quiet: true });
config({ quiet: true });

type Row = Record<string, unknown>;
interface TableSeed {
  table: string;
  conflict: string;
  rows: Row[];
}

/** Stable UUID from a name, so re-running the seed targets the same rows. */
function stableId(name: string): string {
  const h = createHash("sha1").update(`mindfrombooks:${name}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function buildSeed(): TableSeed[] {
  const courses: Row[] = [];
  const books: Row[] = [];
  const phases: Row[] = [];
  const tasks: Row[] = [];
  const bundleId = stableId("bundle:all-access");
  const bundleCourses: Row[] = [];

  COURSES.forEach((c, index) => {
    const id = stableId(`course:${c.slug}`);
    const { sampleDays } = courseAllowances(c.days);
    courses.push({
      id,
      slug: c.slug,
      name: c.name,
      category: c.category,
      emoji: c.emoji,
      accent_color: c.accent_color,
      short_description: c.short_description,
      description: c.description,
      number_reason: c.number_reason,
      outcomes: c.outcomes,
      notice: c.notice,
      days: c.days,
      price_cents: c.price_cents,
      currency: "usd",
      grace_days: courseAllowances(c.days).graceDays,
      status: "published",
      sort_order: index + 1,
      faq: c.faq,
    });
    c.books.forEach((b, i) =>
      books.push({
        id: stableId(`book:${c.slug}:${i}`),
        course_id: id,
        title: b.title,
        author: b.author,
        sort_order: i,
      }),
    );
    c.phases.forEach((p, i) =>
      phases.push({ id: stableId(`phase:${c.slug}:${i}`), course_id: id, ...p }),
    );
    for (let day = 1; day <= c.days; day += 1) {
      const real = c.tasks[day - 1];
      tasks.push(
        real
          ? {
              course_id: id,
              day_number: day,
              title: real.title,
              book_insight: real.book_insight,
              book_reference: real.book_reference,
              instructions: real.instructions,
              response_prompt: real.response_prompt,
              min_response_chars: 0,
              is_sample: day <= sampleDays,
            }
          : {
              course_id: id,
              day_number: day,
              title: `Day ${day} — coming soon`,
              book_insight: "",
              book_reference: "",
              instructions: [],
              response_prompt: "What did you do today, and what did you notice?",
              min_response_chars: 0,
              is_sample: false,
            },
      );
    }
    bundleCourses.push({ bundle_id: bundleId, course_id: id });
  });

  return [
    { table: "app_settings", conflict: "id", rows: [{ id: true }] },
    { table: "courses", conflict: "slug", rows: courses },
    { table: "course_books", conflict: "id", rows: books },
    { table: "course_phases", conflict: "id", rows: phases },
    { table: "tasks", conflict: "course_id,day_number", rows: tasks },
    {
      table: "bundles",
      conflict: "slug",
      rows: [{ id: bundleId, ...BUNDLE, status: "published" }],
    },
    { table: "bundle_courses", conflict: "bundle_id,course_id", rows: bundleCourses },
    {
      table: "coupons",
      conflict: "code",
      rows: [{ ...TEST_COUPON, one_per_user: true, active: true }],
    },
    {
      table: "email_templates",
      conflict: "key",
      rows: Object.values(DEFAULT_TEMPLATES).map((t) => ({ ...t })),
    },
  ];
}

// ---------------------------------------------------------------- SQL output
function sqlValue(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function toSql(seeds: TableSeed[]): string {
  const out: string[] = [
    "-- Generated by `npm run seed:sql` from scripts/seed-data.ts — do not edit by hand.",
    "-- Safe to re-run: existing rows are left untouched.",
    "",
  ];
  for (const { table, conflict, rows } of seeds) {
    if (rows.length === 0) continue;
    const cols = Object.keys(rows[0]);
    out.push(`insert into public.${table} (${cols.join(", ")}) values`);
    out.push(rows.map((r) => `  (${cols.map((c) => sqlValue(r[c])).join(", ")})`).join(",\n"));
    out.push(`on conflict (${conflict}) do nothing;`, "");
  }
  out.push(
    "-- Make yourself an admin (after signing up with this email):",
    "-- update public.profiles set role = 'admin' where lower(email) = lower('you@example.com');",
    "",
  );
  return out.join("\n");
}

// ---------------------------------------------------------------- content migration
/**
 * SQL that brings an EXISTING database up to date with the course content in
 * scripts/content/: course details, books, phases, grace days, sample days and
 * every day's task. Looks courses up by slug, so it works whatever their ids.
 */
function toContentSql(): string {
  const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const json = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const out: string[] = [
    "-- Generated by `npm run content:sql` from scripts/seed-data.ts and scripts/content/.",
    "-- Do not edit by hand: change the content files and regenerate.",
    "--",
    "-- Updates the six courses in place: name and description, inspired-by books,",
    "-- phases, grace days, sample days and all day-by-day tasks.",
    "--",
    "-- Notes:",
    "--  * Task text for every day is replaced. Minimum-character settings are kept.",
    "--  * Grace days change for people who enrol from now on. Existing enrolments",
    "--    keep the number they were bought with.",
    "--  * Books are added if missing; images you uploaded for existing books are kept.",
    "--  * Safe to run more than once.",
    "",
    "begin;",
    "",
  ];

  for (const c of COURSES) {
    const { graceDays, sampleDays } = courseAllowances(c.days);
    const course = `(select id from public.courses where slug = ${q(c.slug)})`;
    out.push(
      `-- ================================================================ ${c.name}`,
      `-- ${c.days} days · ${graceDays} grace days · first ${sampleDays} days are public samples`,
      "update public.courses set",
      `  name = ${q(c.name)},`,
      `  short_description = ${q(c.short_description)},`,
      `  description = ${q(c.description)},`,
      `  number_reason = ${q(c.number_reason)},`,
      `  outcomes = ${json(c.outcomes)},`,
      `  faq = ${json(c.faq)},`,
      `  grace_days = ${graceDays}`,
      `where slug = ${q(c.slug)};`,
      "",
      "insert into public.course_books (course_id, title, author, sort_order)",
      "select c.id, v.title, v.author, v.sort_order",
      "from public.courses c",
      "cross join (values",
      c.books.map((b, i) => `  (${q(b.title)}, ${q(b.author)}, ${i})`).join(",\n"),
      ") as v (title, author, sort_order)",
      `where c.slug = ${q(c.slug)}`,
      "  and not exists (select 1 from public.course_books b where b.course_id = c.id and b.title = v.title);",
      "",
      "update public.course_books b set sort_order = v.sort_order, author = v.author",
      "from (values",
      c.books.map((b, i) => `  (${q(b.title)}, ${q(b.author)}, ${i})`).join(",\n"),
      ") as v (title, author, sort_order)",
      `where b.course_id = ${course} and b.title = v.title;`,
      "",
      `delete from public.course_phases where course_id = ${course};`,
      "insert into public.course_phases (course_id, name, start_day, end_day)",
      "select c.id, v.name, v.start_day, v.end_day",
      "from public.courses c",
      "cross join (values",
      c.phases.map((p) => `  (${q(p.name)}, ${p.start_day}, ${p.end_day})`).join(",\n"),
      ") as v (name, start_day, end_day)",
      `where c.slug = ${q(c.slug)};`,
      "",
      "insert into public.tasks",
      "  (course_id, day_number, title, book_insight, book_reference, instructions, response_prompt, is_sample)",
      "select c.id, v.day_number, v.title, v.book_insight, v.book_reference, v.instructions, v.response_prompt, v.is_sample",
      "from public.courses c",
      "cross join (values",
      c.tasks
        .map(
          (t, i) =>
            `  (${i + 1}, ${q(t.title)}, ${q(t.book_insight)}, ${q(t.book_reference)}, ${json(t.instructions)}, ${q(t.response_prompt)}, ${i + 1 <= sampleDays})`,
        )
        .join(",\n"),
      ") as v (day_number, title, book_insight, book_reference, instructions, response_prompt, is_sample)",
      `where c.slug = ${q(c.slug)}`,
      "on conflict (course_id, day_number) do update set",
      "  title = excluded.title,",
      "  book_insight = excluded.book_insight,",
      "  book_reference = excluded.book_reference,",
      "  instructions = excluded.instructions,",
      "  response_prompt = excluded.response_prompt,",
      "  is_sample = excluded.is_sample;",
      "",
    );
  }
  out.push("commit;", "");
  return out.join("\n");
}

// ---------------------------------------------------------------- Supabase
async function run(seeds: TableSeed[]) {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SECRET_KEY ?? process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error("Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SECRET_KEY in .env.local first.");
  }
  const supabase = createClient(url, key, { auth: { persistSession: false } });

  for (const { table, conflict, rows } of seeds) {
    for (let i = 0; i < rows.length; i += 200) {
      const { error } = await supabase
        .from(table)
        .upsert(rows.slice(i, i + 200), { onConflict: conflict, ignoreDuplicates: true });
      if (error) throw new Error(`${table}: ${error.message}`);
    }
    console.log(`✓ ${table} (${rows.length})`);
  }

  const adminEmail = process.env.ADMIN_EMAIL?.trim().toLowerCase();
  if (!adminEmail) {
    console.log("! ADMIN_EMAIL is not set — no admin was created.");
    return;
  }
  const { data: existing } = await supabase
    .from("profiles")
    .select("id")
    .ilike("email", adminEmail)
    .maybeSingle();
  let adminId = existing?.id as string | undefined;
  if (!adminId) {
    const site = (process.env.NEXT_PUBLIC_SITE_URL || "http://localhost:3000").replace(/\/$/, "");
    const { data, error } = await supabase.auth.admin.inviteUserByEmail(adminEmail, {
      redirectTo: `${site}/auth/callback?next=/reset-password`,
    });
    if (error) throw new Error(`Could not invite ${adminEmail}: ${error.message}`);
    adminId = data.user.id;
    console.log(`✓ invited ${adminEmail} — check that inbox to set a password`);
  }
  const { error } = await supabase.from("profiles").update({ role: "admin" }).eq("id", adminId);
  if (error) throw new Error(`Could not make ${adminEmail} an admin: ${error.message}`);
  console.log(`✓ ${adminEmail} is an admin`);
}

const seeds = buildSeed();
if (process.argv.includes("--content-sql")) {
  process.stdout.write(toContentSql());
} else if (process.argv.includes("--sql")) {
  process.stdout.write(toSql(seeds));
} else {
  run(seeds).catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
